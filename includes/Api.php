<?php

declare(strict_types=1);

namespace CommerceBird\WalletPass;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * API integration for generating and rendering Apple Wallet passes.
 */
final class Api {

	private const CONNECTOR_ENDPOINT          = 'customs/wallet/pass';
	private const PROXY_ACTION                = 'commercebird_wallet_pass';
	public const  PASS_URL_META_KEY           = '_tc_wallet_pass_url';
	public const  GOOGLE_PASS_URL_META_KEY    = '_tc_wallet_google_pass_url';
	public const  GOOGLE_UNAVAILABLE_META_KEY = '_tc_wallet_google_unavailable';

	/**
	 * Response code the API sends for a Google request when Google Wallet is not
	 * configured on its side. The ticket is then flagged with
	 * GOOGLE_UNAVAILABLE_META_KEY so the Google badge stops being offered.
	 * The flag is cleared with the pass cache.
	 */
	private const API_CODE_NOT_CONFIGURED = 501;

	/**
	 * Tickera passes the field_name string to callable-array callbacks, not the post-meta value.
	 * Ticket ids are queued here by queueTicketsForOrder before Tickera renders the column,
	 * then consumed one-by-one by renderWalletButton.
	 *
	 * @var array<int, int>
	 */
	private static array $ticket_queue = array();

	public static function register(): void {
		add_filter( 'tc_owner_info_orders_table_fields_front', array( self::class, 'addWalletColumn' ) );
		// Priority 1 ensures tickets are queued before Tickera renders the column.
		add_action( 'woocommerce_thankyou', array( self::class, 'queueTicketsForOrder' ), 1 );
		add_action( 'woocommerce_account_view_order', array( self::class, 'queueTicketsForOrder' ) );
		add_action( 'woocommerce_email_after_order_table', array( self::class, 'addEmailWalletPass' ), 10, 4 );
		// Proxy endpoint: fetches the .pkpass and re-serves it with the headers iOS Wallet requires.
		// Served from the front end (home URL + query arg) because many server firewalls block
		// /wp-admin/ for anonymous visitors.
		add_action( 'parse_request', array( self::class, 'maybeServeWalletPassProxy' ) );
		// Legacy admin-post.php endpoint, kept so links in already-sent order emails keep working.
		add_action( 'admin_post_' . self::PROXY_ACTION, array( self::class, 'serveWalletPassProxy' ) );
		add_action( 'admin_post_nopriv_' . self::PROXY_ACTION, array( self::class, 'serveWalletPassProxy' ) );
	}

	public static function addWalletColumn( array $fields ): array {
		$fields[] = array(
			'id'                => 'ticket_apple_wallet_pass',
			'field_name'        => self::PASS_URL_META_KEY,
			'field_title'       => __( 'Wallet Pass', 'commercebird-wallet-pass' ),
			'field_type'        => 'function',
			'function'          => array( self::class, 'renderWalletButton' ),
			'field_description' => '',
			'post_field_type'   => 'post_meta',
		);

		return $fields;
	}

	/**
	 * Queues the order's ticket ids so renderWalletButton can consume them in
	 * the order Tickera renders its rows. Hooked to the thank-you page (priority 1,
	 * before Tickera renders the column) and the My Account order view.
	 *
	 * No API call is made here. Passes are generated by the proxy when the
	 * customer clicks a wallet badge, so page loads stay fast and the payment
	 * flow never waits on the CommerceBird API.
	 */
	public static function queueTicketsForOrder( int $order_id ): void {
		if ( ! class_exists( '\Tickera\TC_Orders' ) ) {
			return;
		}
		foreach ( (array) \Tickera\TC_Orders::get_tickets_ids( $order_id ) as $ticket_id ) {
			self::$ticket_queue[] = (int) $ticket_id;
		}
	}

	/**
	 * Whether the WooCommerce order has a paid status (processing or completed by default).
	 *
	 * @param int $order_id WooCommerce order id.
	 */
	private static function isOrderPaid( int $order_id ): bool {
		if ( $order_id <= 0 || ! function_exists( 'wc_get_order' ) ) {
			return false;
		}
		$order = wc_get_order( $order_id );
		return $order instanceof \WC_Order && $order->is_paid();
	}

	/**
	 * Post-meta key that caches a ticket's pass URL for one wallet.
	 *
	 * @param string $wallet 'apple' or 'google'.
	 */
	private static function urlMetaKey( string $wallet ): string {
		return 'google' === $wallet ? self::GOOGLE_PASS_URL_META_KEY : self::PASS_URL_META_KEY;
	}

	/**
	 * Returns one wallet's pass URL for a ticket, calling the CommerceBird API
	 * on the first click of that wallet's badge and serving the cached URL after
	 * that. Apple and Google are generated independently: clicking one badge
	 * never creates the other pass. Ends the request with a message when no
	 * pass can be produced.
	 *
	 * @param int    $ticket_id Tickera ticket (tc_tickets_instances) post id.
	 * @param string $wallet    'apple' or 'google'.
	 */
	private static function getPassUrlForTicket( int $ticket_id, string $wallet ): string {
		$cached = (string) get_post_meta( $ticket_id, self::urlMetaKey( $wallet ), true );
		if ( '' !== $cached ) {
			return $cached;
		}

		if ( 'google' === $wallet && ! self::mayHaveGooglePass( $ticket_id ) ) {
			self::dieWithMessage( 404, __( 'A Google Wallet pass is not available for this ticket.', 'commercebird-wallet-pass' ) );
		}

		// Tickera stores a ticket instance under its WooCommerce order.
		$order_id = (int) wp_get_post_parent_id( $ticket_id );
		if ( ! self::isOrderPaid( $order_id ) ) {
			self::dieWithMessage( 409, __( 'Your payment has not been confirmed yet. Please try again in a few minutes.', 'commercebird-wallet-pass' ) );
		}

		$url = self::generateURLforWallet( $ticket_id, $order_id, $wallet );
		if ( '' === $url ) {
			if ( 'google' === $wallet && ! self::mayHaveGooglePass( $ticket_id ) ) {
				self::dieWithMessage( 404, __( 'A Google Wallet pass is not available for this ticket.', 'commercebird-wallet-pass' ) );
			}
			self::dieWithMessage( 502, __( 'The wallet pass could not be created. Please try again later.', 'commercebird-wallet-pass' ) );
		}

		return $url;
	}

	/**
	 * Whether a Google Wallet badge should be offered for a ticket. It is shown
	 * unless an earlier Google click was answered with "Google Wallet is not
	 * configured". Other failures leave the badge in place so the next click
	 * retries.
	 *
	 * @param int $ticket_id Tickera ticket post id.
	 */
	private static function mayHaveGooglePass( int $ticket_id ): bool {
		return '' === (string) get_post_meta( $ticket_id, self::GOOGLE_UNAVAILABLE_META_KEY, true );
	}

	/**
	 * Generates one wallet's pass via the CommerceBird API, caches its URL in
	 * post-meta, and returns it. Only reached from the proxy, when a customer
	 * clicks that wallet's badge. The Apple URL is re-served with the
	 * Content-Type iOS Wallet requires; the Google URL is redirected to.
	 *
	 * Each wallet is cached under its own key, so a missing Google URL is
	 * retried on the next Google click regardless of the Apple cache. When the
	 * API answers that Google Wallet is not configured, the ticket is flagged
	 * so the Google badge is no longer offered; re-saving the Wallet settings
	 * page clears that flag along with every cached URL.
	 *
	 * @param int    $ticket_id Tickera ticket (tc_tickets_instances) post id.
	 * @param int    $order_id  WooCommerce order id, when known. Threaded through to
	 *                          the API as groupingInfo.groupingId so every ticket in
	 *                          the same order stacks together in Google Wallet. 0 when
	 *                          the caller has no order context; sent to the API as ''.
	 * @param string $wallet    'apple' or 'google'.
	 * @return string The pass URL, or '' when none could be produced.
	 */
	private static function generateURLforWallet( int $ticket_id, int $order_id, string $wallet ): string {
		$meta_key = self::urlMetaKey( $wallet );
		$cached   = (string) get_post_meta( $ticket_id, $meta_key, true );
		if ( '' !== $cached ) {
			return $cached;
		}

		$ticket_meta = get_post_meta( $ticket_id, '', false );
		$event_id    = $ticket_meta['event_id'][0] ?? null;
		$ticket_code = $ticket_meta['ticket_code'][0] ?? '';
		$first_name  = isset( $ticket_meta['first_name'] ) ? reset( $ticket_meta['first_name'] ) : '';
		$last_name   = isset( $ticket_meta['last_name'] ) ? reset( $ticket_meta['last_name'] ) : '';

		if ( empty( $event_id ) || empty( $ticket_code )
			|| ! class_exists( 'Tickera\TC_Event' )
			|| ! class_exists( 'Tickera\TC_Ticket' ) ) {
			return '';
		}

		$event_obj    = new \Tickera\TC_Event( (int) $event_id );
		$location_obj = get_post_meta( (int) $event_id, '', false );
		$ticket       = new \Tickera\TC_Ticket( $ticket_id );

		// Tickera core exposes no meta key for a venue address or an event end
		// time (confirmed in Task 9), so those are sent as ''; the Node API falls
		// back venue_address -> venue_name and omits dateTime.end when empty.
		$result = self::callWalletPassApi(
			$wallet,
			(string) ( $event_obj->details->post_title ?? '' ),
			(string) ( $location_obj['event_location'][0] ?? '' ),
			(string) ( $location_obj['event_date_time'][0] ?? '' ),
			(string) ( $ticket->details->post_title ?? '' ),
			$ticket_id,
			(string) $ticket_code,
			(string) $first_name,
			(string) $last_name,
			(string) $event_id,
			self::toIso8601( (string) ( $location_obj['event_date_time'][0] ?? '' ) ),
			'',
			(string) ( $location_obj['event_location'][0] ?? '' ),
			'',
			$order_id > 0 ? (string) $order_id : ''
		);

		if ( 'google' === $wallet && self::API_CODE_NOT_CONFIGURED === $result['code'] ) {
			update_post_meta( $ticket_id, self::GOOGLE_UNAVAILABLE_META_KEY, '1' );
			return '';
		}

		$url = $result[ $wallet ];
		if ( '' !== $url ) {
			update_post_meta( $ticket_id, $meta_key, $url );
		}

		return $url;
	}

	/**
	 * Builds a signed front-end proxy URL for a .pkpass.
	 * Routing through WordPress lets us set the full set of headers iOS Wallet requires.
	 *
	 * The link points at the home URL rather than /wp-admin/, which server firewalls
	 * often block for anonymous visitors. When the ticket id is known, only the ticket
	 * id is signed and the remote URL is looked up from post meta at download time,
	 * so the remote URL never appears in the link.
	 *
	 * A 'google' link redirects to the ticket's Google Wallet save link instead,
	 * generating it first if needed.
	 *
	 * @param string $pass_url  Remote .pkpass URL, used only when no ticket id is known.
	 * @param int    $ticket_id Tickera ticket (tc_tickets_instances) post id, or 0.
	 * @param string $wallet    'apple' or 'google'. Ignored when no ticket id is known.
	 */
	private static function buildProxyUrl( string $pass_url, int $ticket_id = 0, string $wallet = 'apple' ): string {
		if ( $ticket_id > 0 ) {
			$args = array(
				self::PROXY_ACTION => '1',
				'ticket'           => $ticket_id,
				'sig'              => self::signTicket( $ticket_id ),
			);
			if ( 'google' === $wallet ) {
				$args['wallet'] = 'google';
			}
		} else {
			$args = array(
				self::PROXY_ACTION => '1',
				'pass'             => rawurlencode( $pass_url ),
				'sig'              => self::signPassUrl( $pass_url ),
			);
		}

		return add_query_arg( $args, home_url( '/' ) );
	}

	/**
	 * Signs a ticket id for use in a front-end proxy link.
	 *
	 * @param int $ticket_id Tickera ticket post id.
	 */
	private static function signTicket( int $ticket_id ): string {
		// Prefixed so a ticket signature can never double as a pass-URL signature.
		return hash_hmac( 'sha256', 'ticket:' . $ticket_id, wp_salt( 'auth' ) );
	}

	/**
	 * Signs a remote .pkpass URL for use in a proxy link.
	 *
	 * @param string $pass_url Remote .pkpass URL.
	 */
	private static function signPassUrl( string $pass_url ): string {
		return hash_hmac( 'sha256', $pass_url, wp_salt( 'auth' ) );
	}

	/**
	 * Front-end entry point for the proxy, hooked to parse_request so it runs
	 * before the main query and the theme are loaded.
	 */
	public static function maybeServeWalletPassProxy(): void {
		// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Public download link; authenticity is checked via the HMAC signature.
		if ( ! isset( $_GET[ self::PROXY_ACTION ] ) ) {
			return;
		}

		// Ask page-cache plugins (WP Rocket, W3TC, LiteSpeed, ...) not to cache this response.
		if ( ! defined( 'DONOTCACHEPAGE' ) ) {
			define( 'DONOTCACHEPAGE', true );
		}

		self::serveWalletPassProxy();
	}

	/**
	 * Fetches the .pkpass from the remote URL and re-serves it with the headers
	 * iOS Wallet requires. Accepts either a signed ticket id (current links) or a
	 * signed remote URL (older admin-post.php links in sent emails, and direct URLs).
	 *
	 * For a ticket id, the first click of a badge is what generates that badge's
	 * pass via the API: an Apple click creates only the Apple pass, a Google
	 * click only the Google pass.
	 *
	 * Android cannot open a .pkpass (the browser shows a blank page), so Android
	 * visitors and 'google' links are redirected to the Google Wallet save link.
	 */
	public static function serveWalletPassProxy(): void {
		nocache_headers();

		// phpcs:ignore WordPress.Security.NonceVerification.Recommended, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash -- Public download link; authenticity is checked via the HMAC signature.
		$signature = isset( $_GET['sig'] ) ? (string) wp_unslash( $_GET['sig'] ) : '';
		if ( '' === $signature ) {
			self::dieWithMessage( 403, __( 'This wallet pass link is invalid.', 'commercebird-wallet-pass' ) );
		}

		// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Public download link; authenticity is checked via the HMAC signature.
		$wants_google = isset( $_GET['wallet'] ) && 'google' === $_GET['wallet'];

		// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Public download link; authenticity is checked via the HMAC signature.
		if ( isset( $_GET['ticket'] ) ) {
			// phpcs:ignore WordPress.Security.NonceVerification.Recommended, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash -- Cast to int by absint().
			$ticket_id = absint( $_GET['ticket'] );
			if ( 0 === $ticket_id || ! hash_equals( self::signTicket( $ticket_id ), $signature ) ) {
				self::dieWithMessage( 403, __( 'This wallet pass link is invalid.', 'commercebird-wallet-pass' ) );
			}

			if ( $wants_google || self::isAndroid() ) {
				// phpcs:ignore WordPress.Security.SafeRedirect.wp_redirect_wp_redirect -- Google Wallet save link returned by the CommerceBird API; the ticket id is HMAC-signed.
				wp_redirect( self::getPassUrlForTicket( $ticket_id, 'google' ) );
				exit;
			}

			$pass_url = self::getPassUrlForTicket( $ticket_id, 'apple' );
		} else {
			// phpcs:ignore WordPress.Security.NonceVerification.Recommended, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash -- Validated via the HMAC signature below.
			$encoded_pass = isset( $_GET['pass'] ) ? (string) wp_unslash( $_GET['pass'] ) : '';
			$pass_url     = esc_url_raw( rawurldecode( $encoded_pass ) );

			if ( '' === $pass_url || ! hash_equals( self::signPassUrl( $pass_url ), $signature ) ) {
				self::dieWithMessage( 403, __( 'This wallet pass link is invalid.', 'commercebird-wallet-pass' ) );
			}

			// These links carry no ticket id, so there is no Google pass to send Android to.
			if ( self::isAndroid() ) {
				self::dieWithMessage( 415, __( 'Apple Wallet passes can only be added on an iPhone, iPad or Mac.', 'commercebird-wallet-pass' ) );
			}
		}

		$response = wp_remote_get(
			$pass_url,
			array(
				'timeout'            => 20,
				'redirection'        => 5,
				'reject_unsafe_urls' => true,
			)
		);

		if ( is_wp_error( $response ) || 200 !== wp_remote_retrieve_response_code( $response ) ) {
			self::dieWithMessage( 502, __( 'The wallet pass could not be downloaded. Please try again later.', 'commercebird-wallet-pass' ) );
		}

		$body = wp_remote_retrieve_body( $response );
		if ( '' === $body ) {
			self::dieWithMessage( 502, __( 'The wallet pass could not be downloaded. Please try again later.', 'commercebird-wallet-pass' ) );
		}

		while ( ob_get_level() > 0 ) {
			ob_end_clean();
		}

		header( 'Content-Type: application/vnd.apple.pkpass' );
		header( 'Content-Disposition: inline; filename="ticket.pkpass"' );
		header( 'X-Content-Type-Options: nosniff' );
		header( 'Cache-Control: no-store, no-cache, must-revalidate, max-age=0' );
		header( 'Pragma: no-cache' );
		header( 'Content-Length: ' . strlen( $body ) );

		echo $body; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
		exit;
	}

	/**
	 * Ends a proxy request with a readable page rather than an empty response,
	 * which mobile browsers show as a blank screen.
	 *
	 * @param int    $status  HTTP status code.
	 * @param string $message Message shown to the visitor.
	 */
	private static function dieWithMessage( int $status, string $message ): never {
		wp_die(
			esc_html( $message ),
			esc_html__( 'Wallet Pass', 'commercebird-wallet-pass' ),
			array( 'response' => $status ) // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Integer status code, not output.
		);
		exit;
	}

	/**
	 * Whether the current request comes from an Android device.
	 */
	private static function isAndroid(): bool {
		// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- User agent is only used for basic string checks, not output or API calls.
		$user_agent = isset( $_SERVER['HTTP_USER_AGENT'] ) ? \wp_unslash( (string) $_SERVER['HTTP_USER_AGENT'] ) : '';
		return '' !== $user_agent && false !== stripos( $user_agent, 'Android' );
	}

	public static function addEmailWalletPass( \WC_Order $order, bool $sent_to_admin, bool $plain_text, \WC_Email $email ): void {
		if ( $sent_to_admin ) {
			return;
		}

		if ( ! in_array( $email->id, array( 'customer_processing_order', 'customer_completed_order' ), true ) ) {
			return;
		}

		// if class TC_Orders doesn't exist, it means Tickera isn't active, so skip.
		if ( ! class_exists( '\Tickera\TC_Orders' ) ) {
			return;
		}

		$order_attendees = \Tickera\TC_Orders::get_tickets_ids( $order->get_id() );
		if ( empty( $order_attendees ) ) {
			return;
		}

		// The processing email is sent from inside WooCommerce's payment handling
		// (checkout request or gateway webhook), so no API call is made here: a slow
		// or failing call would break the payment. Every link goes through the proxy,
		// which generates the pass on first click.
		$passes = array();
		foreach ( $order_attendees as $order_attendee_id ) {
			$ticket_id   = (int) $order_attendee_id;
			$ticket_meta = get_post_meta( $ticket_id );
			$ticket_code = isset( $ticket_meta['ticket_code'] ) ? reset( $ticket_meta['ticket_code'] ) : '';
			if ( '' === $ticket_code ) {
				continue;
			}

			$ticket_type_id = isset( $ticket_meta['ticket_type_id'] ) ? reset( $ticket_meta['ticket_type_id'] ) : '';
			$passes[]       = array(
				'title'  => get_the_title( $ticket_type_id ),
				'apple'  => self::buildProxyUrl( '', $ticket_id ),
				'google' => self::mayHaveGooglePass( $ticket_id ) ? self::buildProxyUrl( '', $ticket_id, 'google' ) : '',
			);
		}

		if ( empty( $passes ) ) {
			return;
		}

		if ( $plain_text ) {
			echo "\n" . esc_html__( 'Wallet Passes', 'commercebird-wallet-pass' ) . "\n";
			foreach ( $passes as $pass ) {
				echo esc_html( $pass['title'] ) . ' (Apple Wallet): ' . esc_url( $pass['apple'] ) . "\n";
				if ( '' !== $pass['google'] ) {
					echo esc_html( $pass['title'] ) . ' (Google Wallet): ' . esc_url( $pass['google'] ) . "\n";
				}
			}
			return;
		}

		// Email HTML is rendered at send time, so there is no recipient user agent
		// to branch on. Both badges are shown and the reader picks their own.
		echo '<h2 style="color:#333;font-family:inherit;">' . esc_html__( 'Your Wallet Passes', 'commercebird-wallet-pass' ) . '</h2>';
		foreach ( $passes as $pass ) {
			echo '<p>';
			echo '<strong>' . esc_html( $pass['title'] ) . '</strong><br>';
			self::renderAppleBadgeLink( $pass['apple'] );
			if ( '' !== $pass['google'] ) {
				self::renderGoogleBadge( $pass['google'] );
			}
			echo '</p>';
		}
	}

	/**
	 * Largest icon payload the API accepts, in base64 characters.
	 * Base64 inflates by 4/3, so this is roughly 500 KB of image data.
	 */
	private const MAX_ICON_BASE64_LENGTH = 700000;

	private static function iconToBase64( string $abs_path ): string {
		if ( '' === $abs_path || ! file_exists( $abs_path ) ) {
			return '';
		}
		$bytes = file_get_contents( $abs_path );
		return ( false === $bytes ) ? '' : base64_encode( $bytes );
	}

	/**
	 * Resolves the pass artwork to a PNG small enough for the API.
	 *
	 * get_attached_file() hands back the full-size original, which for a typical
	 * logo upload is far larger than the request budget and gets the whole pass
	 * rejected. Registered intermediate sizes are tried first, largest to
	 * smallest, and only a PNG is returned — Apple will not render anything else
	 * as icon.png.
	 *
	 * @param int $attachment_id Media library ID of the configured icon.
	 * @return string Base64-encoded PNG, or '' to let the API use its default.
	 */
	private static function resolveIconData( int $attachment_id ): string {
		if ( $attachment_id <= 0 ) {
			return '';
		}

		if ( 'image/png' !== \get_post_mime_type( $attachment_id ) ) {
			return '';
		}

		$upload_dir = \wp_get_upload_dir();
		$base_dir   = isset( $upload_dir['basedir'] ) ? (string) $upload_dir['basedir'] : '';
		$candidates = array();

		// Wallet icons top out at 87x87 (29pt @3x); anything larger is wasted bytes.
		foreach ( array( 'medium', 'thumbnail' ) as $size ) {
			$intermediate = \image_get_intermediate_size( $attachment_id, $size );
			if ( is_array( $intermediate ) && ! empty( $intermediate['path'] ) && '' !== $base_dir ) {
				$candidates[] = $base_dir . '/' . $intermediate['path'];
			}
		}

		$candidates[] = (string) \get_attached_file( $attachment_id );

		foreach ( $candidates as $candidate ) {
			$encoded = self::iconToBase64( $candidate );
			if ( '' !== $encoded && strlen( $encoded ) <= self::MAX_ICON_BASE64_LENGTH ) {
				return $encoded;
			}
		}

		if ( class_exists( 'WC_Logger' ) ) {
			wc_get_logger()->warning(
				'Wallet Pass icon is too large to send; the default icon will be used. Upload a PNG of about 87x87 pixels.',
				array( 'source' => 'commercebird-wallet-pass' )
			);
		}

		return '';
	}

	/**
	 * Public URL of the configured icon.
	 *
	 * Google Wallet fetches class images server-side and rejects base64, so the
	 * URL is sent alongside the base64 Apple still needs.
	 *
	 * @param int $attachment_id Media library ID of the configured icon.
	 * @return string Public URL, or '' when there is nothing usable.
	 */
	private static function resolveIconUrl( int $attachment_id ): string {
		if ( $attachment_id <= 0 ) {
			return '';
		}

		$url = \wp_get_attachment_url( $attachment_id );
		if ( ! is_string( $url ) || '' === $url ) {
			return '';
		}

		// Google fetches the image itself, so an http:// URL fails class insertion.
		return str_starts_with( $url, 'https://' ) ? $url : '';
	}

	/**
	 * Normalises an event date string to ISO 8601 in the site's timezone.
	 *
	 * WordPress forces PHP's default timezone to UTC, so strtotime() on
	 * Tickera's local wall-clock event_date_time (e.g. "2026-09-01 20:00:00")
	 * would produce the epoch for that time treated as UTC. Handing that
	 * epoch to wp_date() then converts it into the site timezone, applying
	 * the offset a second time (20:00 local becomes 22:00 on a UTC+2 site).
	 * date_create_immutable() is given the site timezone directly so the raw
	 * string is interpreted as local wall-clock time exactly once.
	 *
	 * The API omits the pass dateTime block for an empty string, so an
	 * unparseable date degrades the pass instead of failing it.
	 *
	 * @param string $raw Raw value from the event post meta.
	 * @return string ISO 8601 timestamp, or ''.
	 */
	private static function toIso8601( string $raw ): string {
		$value = trim( $raw );
		if ( '' === $value ) {
			return '';
		}

		$dt = \date_create_immutable( $value, \wp_timezone() );
		return $dt ? $dt->format( 'c' ) : '';
	}

	/**
	 * Normalises a colour-picker value to #rrggbb.
	 *
	 * Anything the API cannot parse silently degrades the pass to the default
	 * grey, so shorthand and unhashed values are expanded here.
	 *
	 * @param string $color    Raw value from the colour picker.
	 * @param string $fallback Colour to use when $color cannot be parsed.
	 * @return string Colour as #rrggbb.
	 */
	private static function normalizeHexColor( string $color, string $fallback = '#aaaaaa' ): string {
		$value = ltrim( trim( $color ), '#' );

		if ( 3 === strlen( $value ) && ctype_xdigit( $value ) ) {
			$value = $value[0] . $value[0] . $value[1] . $value[1] . $value[2] . $value[2];
		}

		if ( 6 !== strlen( $value ) || ! ctype_xdigit( $value ) ) {
			return $fallback;
		}

		return '#' . strtolower( $value );
	}

	public static function invalidatePassCache( int $ticket_id ): void {
		delete_post_meta( $ticket_id, self::PASS_URL_META_KEY );
		delete_post_meta( $ticket_id, self::GOOGLE_PASS_URL_META_KEY );
		delete_post_meta( $ticket_id, self::GOOGLE_UNAVAILABLE_META_KEY );
	}

	/**
	 * A meta_query matching every ticket that holds any cached pass state.
	 * Apple and Google are generated separately, so a ticket can have a Google
	 * URL without an Apple one.
	 *
	 * @return array<int|string, mixed>
	 */
	public static function cachedPassMetaQuery(): array {
		$query = array( 'relation' => 'OR' );
		foreach ( array( self::PASS_URL_META_KEY, self::GOOGLE_PASS_URL_META_KEY, self::GOOGLE_UNAVAILABLE_META_KEY ) as $key ) {
			$query[] = array(
				'key'     => $key,
				'compare' => 'EXISTS',
			);
		}
		return $query;
	}

	/**
	 * Asks the CommerceBird API for one wallet's pass.
	 *
	 * @param string $wallet        'apple' or 'google'. Sent as `wallet` so the API
	 *                              creates only that pass.
	 * @param string $event_title   Event name.
	 * @param string $location      Event location as stored by Tickera.
	 * @param string $datetime      Raw event date/time as stored by Tickera.
	 * @param string $ticket_title  Ticket type name.
	 * @param int    $ticket_id     Tickera ticket post id.
	 * @param string $ticket_code   Ticket code encoded in the barcode.
	 * @param string $first_name    Attendee first name.
	 * @param string $last_name     Attendee last name.
	 * @param string $event_id      Tickera event post id.
	 * @param string $event_start   Event start as ISO 8601, or ''.
	 * @param string $event_end     Event end as ISO 8601, or ''.
	 * @param string $venue_name    Venue name.
	 * @param string $venue_address Venue address, or ''.
	 * @param string $order_id      WooCommerce order id, or ''.
	 * @return array{apple: string, google: string, code: int} code is the API's
	 *               response code, or 0 when no response was received.
	 */
	private static function callWalletPassApi(
		string $wallet,
		string $event_title,
		string $location,
		string $datetime,
		string $ticket_title,
		int $ticket_id,
		string $ticket_code,
		string $first_name,
		string $last_name,
		string $event_id = '',
		string $event_start = '',
		string $event_end = '',
		string $venue_name = '',
		string $venue_address = '',
		string $order_id = ''
	): array {
		$settings = Admin::getSettings();

		$payload = array(
			'wallet'            => $wallet,
			'event_title'       => $event_title,
			'location'          => $location,
			'datetime'          => $datetime,
			'ticket_title'      => $ticket_title,
			'ticket_id'         => $ticket_id,
			'ticket_code'       => $ticket_code,
			'first_name'        => $first_name,
			'last_name'         => $last_name,
			'icon_data'         => self::resolveIconData( (int) ( $settings['icon_file_id'] ?? 0 ) ),
			'logo_text'         => (string) ( $settings['logo_text'] ?? '' ),
			'background_color'  => self::normalizeHexColor( (string) ( $settings['background_color'] ?? '' ) ),
			'organisation_name' => (string) ( $settings['organisation_name'] ?? '' ),
			// Google Wallet needs a fetchable image, a real timestamp and a split venue.
			'icon_url'          => self::resolveIconUrl( (int) ( $settings['icon_file_id'] ?? 0 ) ),
			'event_id'          => $event_id,
			'event_start'       => $event_start,
			'event_end'         => $event_end,
			'venue_name'        => $venue_name,
			'venue_address'     => $venue_address,
			'homepage_uri'      => \home_url(),
			'order_id'          => $order_id,
		);

		$failed = array(
			'apple'  => '',
			'google' => '',
			'code'   => 0,
		);

		if ( ! class_exists( 'CommerceBird\\Admin\\Connectors\\Connector' ) ) {
			if ( class_exists( 'WC_Logger' ) ) {
				wc_get_logger()->error( 'Connector class not found. Ensure the CommerceBird plugin is active.', array( 'source' => 'tickera-wallet-pass' ) );
			}
			return $failed;
		}

		$connector = new \CommerceBird\Admin\Connectors\Connector();
		$response  = $connector->request( self::CONNECTOR_ENDPOINT, 'POST', $payload );

		if ( is_wp_error( $response ) ) {
			if ( class_exists( 'WC_Logger' ) ) {
				wc_get_logger()->error( 'Wallet Pass API request failed (' . $wallet . '): ' . $response->get_error_message(), array( 'source' => 'tickera-wallet-pass' ) );
			}
			return $failed;
		}

		$code = is_array( $response ) ? (int) ( $response['code'] ?? 0 ) : 0;
		if ( 200 !== $code ) {
			if ( class_exists( 'WC_Logger' ) ) {
				$message = is_array( $response ) ? ( $response['message'] ?? 'unexpected response' ) : 'unexpected response';
				wc_get_logger()->error( 'Wallet Pass API error (' . $wallet . '): ' . $message, array( 'source' => 'tickera-wallet-pass' ) );
			}
			$failed['code'] = $code;
			return $failed;
		}

		$data       = $response['data'] ?? array();
		$pass_url   = $data['pass_url'] ?? $data['url'] ?? null;
		$google_url = $data['google_pass_url'] ?? null;

		return array(
			'apple'  => is_string( $pass_url ) ? \esc_url_raw( $pass_url ) : '',
			'google' => is_string( $google_url ) ? \esc_url_raw( $google_url ) : '',
			'code'   => $code,
		);
	}

	/**
	 * Renders the Apple and/or Google wallet badge(s) for a ticket.
	 *
	 * Tickera normally passes the field_name string, not the meta value, to
	 * callable-array callbacks, so the ticket comes from the queue filled by
	 * queueTicketsForOrder. One entry is consumed per row so the queue stays
	 * aligned with Tickera's rows. Some Tickera versions and third-party callers
	 * pass the cached Apple URL instead; with nothing queued, a string starting
	 * with "http" is still rendered as an Apple badge.
	 *
	 * The badges link to the proxy, which calls the API on the first click.
	 *
	 * @param string $pass_url Field name, a cached Apple URL, or ''.
	 */
	public static function renderWalletButton( $pass_url = '' ): void {
		$ticket_id = (int) ( array_shift( self::$ticket_queue ) ?? 0 );

		if ( 0 === $ticket_id ) {
			if ( is_string( $pass_url ) && str_starts_with( $pass_url, 'http' ) && ! self::isAndroid() ) {
				self::renderAppleBadgeLink( self::buildProxyUrl( $pass_url ) );
			}
			return;
		}

		// Android cannot open a .pkpass, so only the Google badge is offered there.
		if ( self::isAndroid() ) {
			if ( self::mayHaveGooglePass( $ticket_id ) ) {
				self::renderGoogleBadge( self::buildProxyUrl( '', $ticket_id, 'google' ) );
			}
			return;
		}

		self::renderAppleBadgeLink( self::buildProxyUrl( '', $ticket_id ) );
	}

	/**
	 * Echoes the Apple Wallet badge linking to a signed proxy link.
	 *
	 * @param string $proxy_url Signed proxy link built by buildProxyUrl().
	 */
	private static function renderAppleBadgeLink( string $proxy_url ): void {
		$badge = plugins_url( 'includes/add-to-apple-wallet.png', dirname( __DIR__ ) . '/tickera-wallet-pass.php' );
		echo '<a href="' . esc_url( $proxy_url ) . '" rel="noopener noreferrer">'
			. '<img src="' . esc_url( $badge ) . '" width="100" alt="' . esc_attr__( 'Add to Apple Wallet', 'commercebird-wallet-pass' ) . '" />'
			. '</a>';
	}

	/**
	 * Echoes the Google Wallet badge. The link is a signed proxy link, which
	 * generates the pass if needed and then redirects to Google's save page.
	 *
	 * The official "Add to Google Wallet" badge is trademark-protected artwork that
	 * Google requires be used unmodified, so it ships as a separate binary asset
	 * (includes/add-to-google-wallet.png) rather than being generated here. Until
	 * that file is present, a plain accessible text link is rendered instead of an
	 * <img> that would 404.
	 *
	 * @param string $google_url Signed proxy link built by buildProxyUrl().
	 */
	private static function renderGoogleBadge( string $google_url ): void {
		$badge_path = __DIR__ . '/add-to-google-wallet.png';

		if ( file_exists( $badge_path ) ) {
			$badge = plugins_url( 'includes/add-to-google-wallet.png', dirname( __DIR__ ) . '/tickera-wallet-pass.php' );
			echo '<a href="' . esc_url( $google_url ) . '" rel="noopener noreferrer">'
				. '<img src="' . esc_url( $badge ) . '" width="100" alt="' . esc_attr__( 'Add to Google Wallet', 'commercebird-wallet-pass' ) . '" />'
				. '</a>';
			return;
		}

		echo '<a href="' . esc_url( $google_url ) . '" rel="noopener noreferrer">'
			. esc_html__( 'Add to Google Wallet', 'commercebird-wallet-pass' )
			. '</a>';
	}
